// Params 是一档 ML-DSA 参数。
type Params struct {
	Name   string
	K, L   int
	Eta    int
	Tau    int
	Beta   int
	Gamma1 int
	Gamma2 int
	Omega  int
	CTilde int
}

var (
	MLDSA44 = Params{"ML-DSA-44", 4, 4, 2, 39, 78, 1 << 17, (Q - 1) / 88, 80, 32}
	MLDSA65 = Params{"ML-DSA-65", 6, 5, 4, 49, 196, 1 << 19, (Q - 1) / 32, 55, 48}
	MLDSA87 = Params{"ML-DSA-87", 8, 7, 2, 60, 120, 1 << 19, (Q - 1) / 32, 75, 64}
)

var AllParams = []Params{MLDSA44, MLDSA65, MLDSA87}

// PolyT1Bytes 等派生尺寸与 ref/params.h:50-70 一致。
func (p Params) PolyT1Bytes() int { return 320 }

func (p Params) PolyT0Bytes() int { return 416 }

func (p Params) PolyVecHBytes() int { return p.Omega + p.K }

func (p Params) PolyZBytes() int {
	if p.Gamma1 == 1<<17 {
		return 576
	}
	return 640
}

func (p Params) PolyW1Bytes() int {
	if p.Gamma2 == (Q-1)/88 {
		return 192
	}
	return 128
}

func (p Params) PolyEtaBytes() int {
	if p.Eta == 2 {
		return 96
	}
	return 128
}

func (p Params) PKBytes() int {
	return 32 + p.K*p.PolyT1Bytes()
}

func (p Params) SKBytes() int {
	return 2*32 + 64 + p.L*p.PolyEtaBytes() + p.K*p.PolyEtaBytes() + p.K*p.PolyT0Bytes()
}

func (p Params) SigBytes() int {
	return p.CTilde + p.L*p.PolyZBytes() + p.Omega + p.K
}

